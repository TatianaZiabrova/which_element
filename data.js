export function getResult(answers) {
  if (!Array.isArray(answers) || answers.length !== questions.length || answers.some((a, i) => !Number.isInteger(a) || !questions[i].options[a])) throw new Error('Нужно ответить на все восемь вопросов.');
  const scores = Object.fromEntries(Object.keys(elements).map(key => [key, 0]));
  const first = {...scores};
  const chosen = answers.map((a, i) => questions[i].options[a]);
  for (const {primary, secondary} of chosen) { scores[primary] += 2; scores[secondary]++; first[primary]++; }
  const max = Math.max(...Object.values(scores));
  let leaders = Object.keys(scores).filter(key => scores[key] === max);
  const topFirst = Math.max(...leaders.map(key => first[key]));
  leaders = leaders.filter(key => first[key] === topFirst);
  for (const option of chosen.toReversed()) {
    for (const key of [option.primary, option.secondary]) if (leaders.includes(key)) return key;
  }
}
